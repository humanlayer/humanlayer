import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

import { runCli } from '../cli'
import { caddyConfigPath } from '../lib/caddy'
import { emptyRegistry, readRegistry, writeRegistry } from '../lib/registry'

const temporaryDirectories: string[] = []

afterEach(async () => {
	await Promise.all(temporaryDirectories.splice(0).map((path) => rm(path, { recursive: true, force: true })))
})

const cliDependencies = {}

function captureIO() {
	const stdout: string[] = []
	const stderr: string[] = []
	return {
		stdout,
		stderr,
		io: { stdout: (text: string) => stdout.push(text), stderr: (text: string) => stderr.push(text) },
	}
}

describe.skipIf(Boolean(process.env.CI))('devstack CLI', () => {
	it('syncs, repeats idempotently, and reports a stack from temp paths', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-repo-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const baseArgs = ['--stack', 'Feature/One', '--global-stacks', registryPath, '--repo-root', repoRoot]

		const sync = captureIO()
		expect(await runCli(['sync', ...baseArgs], sync.io, cliDependencies)).toBe(0)
		expect(sync.stderr).toEqual([])
		expect(sync.stdout.join('')).toContain('Stack: feature-one')
		expect(sync.stdout.join('')).toContain('https://app.feature-one.localhost')

		const envAfterSync = await readFile(join(repoRoot, '.env'), 'utf8')
		expect(envAfterSync.match(/# <devstack-autogenerated>/g)).toHaveLength(1)
		expect(envAfterSync).toContain('DEVSTACK_COMPOSE_PROJECT=devstk-feature-one')
		expect(envAfterSync).toContain('DEVSTACK_POSTGRES_VOLUME=riptide-feature-one-postgres')
		expect(envAfterSync).toContain('DEVSTACK_ELECTRIC_REPLICATION_STREAM_ID=feature_one')
		expect(JSON.parse(await readFile(join(repoRoot, '.devstack.json'), 'utf8'))).toEqual({ stackId: 'feature-one' })

		// sync owns the generated Caddy config even when process convergence is stubbed out.
		expect(await readFile(caddyConfigPath(registryPath), 'utf8')).toContain('ui.feature-one.localhost')

		const registryAfterSync = JSON.parse(await readFile(registryPath, 'utf8')) as {
			stacks: Record<string, { ports: object }>
		}
		expect(registryAfterSync).not.toHaveProperty('selectedStackId')

		// A second sync is a no-op that keeps the allocated ports stable.
		const repeat = captureIO()
		expect(
			await runCli(
				['sync', '--global-stacks', registryPath, '--repo-root', repoRoot],
				repeat.io,
				cliDependencies,
			),
		).toBe(0)
		const registryAfterRepeat = JSON.parse(await readFile(registryPath, 'utf8')) as {
			stacks: Record<string, { ports: object }>
		}
		expect(registryAfterRepeat.stacks['feature-one']?.ports).toEqual(registryAfterSync.stacks['feature-one']?.ports)
		expect((await readFile(join(repoRoot, '.env'), 'utf8')).match(/# <devstack-autogenerated>/g)).toHaveLength(1)

		const status = captureIO()
		expect(
			await runCli(['status', '--global-stacks', registryPath, '--repo-root', repoRoot, '--json'], status.io),
		).toBe(0)
		const statusJson = JSON.parse(status.stdout.join('')) as {
			id: string
			generatedEnvFresh: boolean
			routes: { api: string }
		}
		expect(statusJson).toMatchObject({
			id: 'feature-one',
			generatedEnvFresh: true,
			routes: { api: 'https://api.feature-one.localhost' },
		})
	})

	it('uses explicit --stack instead of the workspace-local stack ID', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-override-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-override-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--global-stacks', registryPath, '--repo-root', repoRoot]

		expect(await runCli(['sync', '--stack', 'local-stack', ...paths], captureIO().io, cliDependencies)).toBe(0)
		expect(await runCli(['sync', '--stack', 'override-stack', ...paths], captureIO().io, cliDependencies)).toBe(0)

		const localStatus = captureIO()
		expect(await runCli(['status', ...paths, '--json'], localStatus.io)).toBe(0)
		expect(JSON.parse(localStatus.stdout.join(''))).toMatchObject({ id: 'override-stack' })

		const explicitStatus = captureIO()
		expect(await runCli(['status', '--stack', 'local-stack', ...paths, '--json'], explicitStatus.io)).toBe(0)
		expect(JSON.parse(explicitStatus.stdout.join(''))).toMatchObject({ id: 'local-stack' })
	})

	it('summarizes every registry stack when no explicit or workspace-local stack is selected', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-no-local-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-no-local-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const otherRepoRoot = await mkdtemp(join(tmpdir(), 'devstack-other-test-'))
		temporaryDirectories.push(otherRepoRoot)
		await runCli(
			['sync', '--stack', 'z-stack', '--global-stacks', registryPath, '--repo-root', stateRoot],
			captureIO().io,
			cliDependencies,
		)
		await runCli(
			['sync', '--stack', 'a-stack', '--global-stacks', registryPath, '--repo-root', otherRepoRoot],
			captureIO().io,
			cliDependencies,
		)

		const output = captureIO()
		expect(await runCli(['status', '--global-stacks', registryPath, '--repo-root', repoRoot], output.io)).toBe(0)
		expect(output.stderr).toEqual([])
		expect(output.stdout.join('')).toBe(
			`Local organization: unconfigured\n\na-stack  ${otherRepoRoot}\nz-stack  ${stateRoot}\n\nRun \`bun --bun run devstack status --stack <id>\` for detailed URLs and ports.\n`,
		)
		expect(output.stdout.join('')).not.toContain('https://')
	})

	it('emits only registry path, stack IDs, and worktree paths for unselected JSON status', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-summary-json-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-summary-json-state-test-'))
		const stackRoot = await mkdtemp(join(tmpdir(), 'devstack-summary-json-stack-test-'))
		temporaryDirectories.push(repoRoot, stateRoot, stackRoot)
		const registryPath = join(stateRoot, 'default.json')
		await runCli(
			['sync', '--stack', 'elsewhere', '--global-stacks', registryPath, '--repo-root', stackRoot],
			captureIO().io,
			cliDependencies,
		)

		const output = captureIO()
		expect(
			await runCli(['status', '--global-stacks', registryPath, '--repo-root', repoRoot, '--json'], output.io),
		).toBe(0)
		expect(JSON.parse(output.stdout.join(''))).toEqual({
			registryPath,
			stacks: [{ id: 'elsewhere', worktreePath: stackRoot }],
		})
	})

	it('reports detailed API health in human and JSON output without failing', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-health-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-health-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--stack', 'health-test', '--global-stacks', registryPath, '--repo-root', repoRoot]
		await runCli(['sync', ...paths], captureIO().io, cliDependencies)

		const passed = captureIO()
		expect(await runCli(['status', ...paths], passed.io, { probeApiHealth: async () => true })).toBe(0)
		expect(passed.stdout.join('')).toContain(
			'API healthcheck: passed (stack is already running via bun --bun run riptide or equivalent)',
		)

		const failed = captureIO()
		expect(await runCli(['status', '--json', ...paths], failed.io, { probeApiHealth: async () => false })).toBe(0)
		expect(JSON.parse(failed.stdout.join('')).apiHealth).toEqual({
			url: 'https://api.health-test.localhost/health',
			status: 'failed',
		})
	})

	it('does not probe API health for the registry-only summary', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-health-summary-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-health-summary-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const probeCalls: string[] = []

		expect(
			await runCli(
				['status', '--global-stacks', join(stateRoot, 'default.json'), '--repo-root', repoRoot],
				captureIO().io,
				{ probeApiHealth: async (url) => (probeCalls.push(url), true) },
			),
		).toBe(0)
		expect(probeCalls).toEqual([])
	})

	it('returns an actionable error for an unknown stack', async () => {
		const directory = await mkdtemp(join(tmpdir(), 'devstack-empty-test-'))
		temporaryDirectories.push(directory)
		const output = captureIO()
		expect(
			await runCli(['status', '--stack', 'missing', '--global-stacks', join(directory, 'state.json')], output.io),
		).toBe(1)
		expect(output.stderr.join('')).toContain('is not registered')
	})

	it('rejects retired subcommands after the surface collapse', async () => {
		const directory = await mkdtemp(join(tmpdir(), 'devstack-retired-test-'))
		temporaryDirectories.push(directory)
		const registryPath = join(directory, 'state.json')
		for (const command of ['init', 'list', 'seed', 'wait', 'caddy', 'native']) {
			const output = captureIO()
			expect(await runCli([command, '--global-stacks', registryPath], output.io, cliDependencies)).toBe(1)
		}
	})

	it('exposes only the supported command interface', async () => {
		const output = captureIO()
		expect(await runCli(['--help'], output.io)).toBe(0)
		const help = output.stdout.join('')
		for (const command of ['sync', 'reallocate', 'down', 'status', 'set-local-org']) expect(help).toContain(command)
		for (const command of ['init', 'list', 'seed', 'wait', 'caddy', 'native']) {
			expect(help).not.toMatch(new RegExp(`^\\s+${command}(?:\\s|$)`, 'm'))
		}
	})

	it('prints an ordered plan and mutates nothing on sync --dry-run', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-dry-repo-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-dry-state-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--stack', 'demo/plan', '--global-stacks', registryPath, '--repo-root', repoRoot]

		const plain = captureIO()
		expect(await runCli(['sync', '--dry-run', ...paths], plain.io, cliDependencies)).toBe(0)
		const out = plain.stdout.join('')
		expect(out).toContain('Dry run for stack "demo-plan"')
		expect(out).toContain('reconcile WorkOS resources: create')
		expect(out).toContain('persist registry record: create')
		expect(out).toContain('install workspace projection: create')
		expect(out).toContain('install Caddy routes: create')
		expect(out).toContain('Resolved values:')
		expect(out).toContain('port api:')
		expect(out).toContain('route api: https://api.demo-plan.localhost')
		expect(out).not.toContain('wait for Postgres and apply migrations')
		expect(out).not.toContain('seed local organization')

		// Nothing was written: no registry entry, no env block, no workspace config, no Caddy config.
		expect((await readRegistry(registryPath)).stacks).toEqual({})
		await expect(readFile(join(repoRoot, '.env'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })
		await expect(readFile(join(repoRoot, '.devstack.json'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })
		await expect(readFile(caddyConfigPath(registryPath), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })

		// --compose --seed extend the plan with bootstrap steps but still mutate nothing.
		await writeRegistry(registryPath, {
			...emptyRegistry(),
			defaults: {
				organization: { id: 'organization-id', workosOrganizationId: 'workos-id', name: 'Local Org' },
			},
		})
		const full = captureIO()
		expect(await runCli(['sync', '--dry-run', '--compose', '--seed', ...paths], full.io, cliDependencies)).toBe(0)
		const fullOut = full.stdout.join('')
		expect(fullOut).toContain('start Compose stack')
		expect(fullOut).toContain('wait for Postgres and apply migrations')
		expect(fullOut).toContain('seed local organization')
		expect((await readRegistry(registryPath)).stacks).toEqual({})
	})

	it('emits valid JSON for a dry-run plan without writing projections', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-json-dry-repo-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-json-dry-state-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--stack', 'json/plan', '--global-stacks', registryPath, '--repo-root', repoRoot]
		const output = captureIO()

		expect(await runCli(['sync', '--dry-run', '--json', ...paths], output.io, cliDependencies)).toBe(0)
		const plan = JSON.parse(output.stdout.join('')) as {
			stackId: string
			desired: { ports: Record<string, number>; routes: Record<string, string> }
			actions: Array<{ type: string }>
		}
		expect(plan.stackId).toBe('json-plan')
		expect(plan.desired.ports.api).toBeTypeOf('number')
		expect(plan.desired.routes.api).toBe('https://api.json-plan.localhost')
		expect(plan.actions.map(({ type }) => type)).toContain('persist-registry')
		expect((await readRegistry(registryPath)).stacks).toEqual({})
		await expect(readFile(join(repoRoot, '.env'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })
		await expect(readFile(join(repoRoot, '.devstack.json'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })
		await expect(readFile(caddyConfigPath(registryPath), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' })
	})

	it('configures local organization defaults and suggests the command when missing', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-org-test-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-org-state-test-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--global-stacks', registryPath, '--repo-root', repoRoot]
		await runCli(['sync', '--stack', 'org-test', ...paths], captureIO().io, cliDependencies)

		const configured = captureIO()
		expect(
			await runCli(
				[
					'set-local-org',
					'--workos-org-id',
					'org_workos',
					'--name',
					'Local Org',
					'--organization-id',
					'019b049c-950d-7baa-b9a8-b9364599319b',
					...paths,
				],
				configured.io,
			),
		).toBe(0)
		const registry = JSON.parse(await readFile(registryPath, 'utf8')) as {
			defaults: { organization: { id: string; workosOrganizationId: string; name: string } }
		}
		expect(registry.defaults.organization).toEqual({
			id: '019b049c-950d-7baa-b9a8-b9364599319b',
			workosOrganizationId: 'org_workos',
			name: 'Local Org',
		})
		const synced = captureIO()
		expect(await runCli(['sync', '--stack', 'org-test', ...paths], synced.io, cliDependencies)).toBe(0)
		expect(JSON.parse((await readFile(join(repoRoot, '.devstack.json'), 'utf8')).trim()).stackId).toBe('org-test')
		expect(await readFile(join(repoRoot, '.env'), 'utf8')).toContain(
			'RIPTIDE_DAEMON_ORGANIZATION_ID=019b049c-950d-7baa-b9a8-b9364599319b',
		)
		expect(synced.stdout.join('')).toContain('Generated env: fresh')

		const textStatus = captureIO()
		expect(await runCli(['status', '--stack', 'org-test', ...paths], textStatus.io, cliDependencies)).toBe(0)
		expect(textStatus.stdout.join('')).toContain(
			'Local organization: Local Org (internal: 019b049c-950d-7baa-b9a8-b9364599319b, WorkOS: org_workos)',
		)

		await runCli(
			['set-local-org', '--workos-org-id', 'org_replaced', '--name', 'Renamed Org', ...paths],
			captureIO().io,
		)
		expect((await readRegistry(registryPath)).defaults?.organization?.id).toBe(
			'019b049c-950d-7baa-b9a8-b9364599319b',
		)

		const jsonStatus = captureIO()
		expect(
			await runCli(['status', '--json', '--stack', 'org-test', ...paths], jsonStatus.io, cliDependencies),
		).toBe(0)
		expect(JSON.parse(jsonStatus.stdout.join('')).localOrganization).toEqual({
			id: '019b049c-950d-7baa-b9a8-b9364599319b',
			workosOrganizationId: 'org_replaced',
			name: 'Renamed Org',
		})
		expect(JSON.parse(jsonStatus.stdout.join('')).generatedEnvFresh).toBe(true)

		await runCli(
			[
				'set-local-org',
				'--workos-org-id',
				'org_replaced',
				'--name',
				'Renamed Org',
				'--organization-id',
				'019b049c-950d-7baa-b9a8-b9364599319c',
				...paths,
			],
			captureIO().io,
		)
		expect((await readRegistry(registryPath)).defaults?.organization?.id).toBe(
			'019b049c-950d-7baa-b9a8-b9364599319c',
		)
		const replacedStatus = captureIO()
		await runCli(['status', '--json', '--stack', 'org-test', ...paths], replacedStatus.io, cliDependencies)
		expect(JSON.parse(replacedStatus.stdout.join('')).generatedEnvFresh).toBe(false)
	})

	it('reallocates fresh ports for a registered stack while preserving identity and secrets', async () => {
		const repoRoot = await mkdtemp(join(tmpdir(), 'devstack-realloc-repo-'))
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-realloc-state-'))
		temporaryDirectories.push(repoRoot, stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const paths = ['--stack', 'realloc-me', '--global-stacks', registryPath, '--repo-root', repoRoot]

		expect(await runCli(['sync', ...paths], captureIO().io, cliDependencies)).toBe(0)
		const before = (await readRegistry(registryPath)).stacks['realloc-me']!

		const output = captureIO()
		expect(await runCli(['reallocate', ...paths], output.io, cliDependencies)).toBe(0)
		expect(output.stderr).toEqual([])
		expect(output.stdout.join('')).toContain('Reallocated ports for stack "realloc-me"')

		const after = (await readRegistry(registryPath)).stacks['realloc-me']!
		// Identity, secrets, and volumes are carried forward untouched...
		expect(after.id).toBe(before.id)
		expect(after.createdAt).toBe(before.createdAt)
		expect(after.postgres.postgresPassword).toBe(before.postgres.postgresPassword)
		expect(after.postgres.postgresVolume).toBe(before.postgres.postgresVolume)
		expect(after.electric.electricSecret).toBe(before.electric.electricSecret)
		expect(after.redis?.volume).toBe(before.redis?.volume)
		// ...while the persisted record reflects a complete, internally consistent port set.
		expect(new Set(Object.values(after.ports)).size).toBe(Object.values(after.ports).length)
		expect(after.postgres.postgresPort).toBe(after.ports.postgres)
		expect(after.api.port).toBe(after.ports.api)
	})

	it('will not reallocate a stack that is not registered', async () => {
		const stateRoot = await mkdtemp(join(tmpdir(), 'devstack-realloc-missing-'))
		temporaryDirectories.push(stateRoot)
		const registryPath = join(stateRoot, 'default.json')
		const output = captureIO()
		expect(
			await runCli(
				['reallocate', '--stack', 'ghost', '--global-stacks', registryPath],
				output.io,
				cliDependencies,
			),
		).toBe(1)
		expect(output.stderr.join('')).toContain('is not registered')
	})
})
