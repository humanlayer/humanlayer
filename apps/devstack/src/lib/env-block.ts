export const DEVSTACK_ENV_START = '# <devstack-autogenerated>'
export const DEVSTACK_ENV_END = '# </devstack-autogenerated>'
export const DEVSTACK_ENV_WARNING = '# AUTO GENERATED BY bun --bun run devstack ... DO NOT EDIT THIS BLOCK'
const AUTHORITATIVE_ENV_NAMES = ['RIPTIDE_DAEMON_ORGANIZATION_ID'] as const

export function isDevstackEnvBlockFresh(existingEnv: string, generatedLines: readonly string[]): boolean {
	const startIndex = existingEnv.indexOf(DEVSTACK_ENV_START)
	const endIndex = existingEnv.indexOf(DEVSTACK_ENV_END)
	if (startIndex === -1 || endIndex < startIndex) return false
	if (existingEnv.indexOf(DEVSTACK_ENV_START, startIndex + DEVSTACK_ENV_START.length) !== -1) return false
	if (existingEnv.indexOf(DEVSTACK_ENV_END, endIndex + DEVSTACK_ENV_END.length) !== -1) return false

	const expected = [DEVSTACK_ENV_START, DEVSTACK_ENV_WARNING, ...generatedLines, DEVSTACK_ENV_END].join('\n')
	const actual = existingEnv.slice(startIndex, endIndex + DEVSTACK_ENV_END.length)
	const outsideBlock = `${existingEnv.slice(0, startIndex)}${existingEnv.slice(endIndex + DEVSTACK_ENV_END.length)}`
	return actual === expected && !containsAuthoritativeEnvAssignment(outsideBlock)
}

export function replaceDevstackEnvBlock(existingEnv: string, generatedLines: readonly string[]): string {
	const startIndex = existingEnv.indexOf(DEVSTACK_ENV_START)
	const endIndex = existingEnv.indexOf(DEVSTACK_ENV_END)
	const nextBlock = [DEVSTACK_ENV_START, DEVSTACK_ENV_WARNING, ...generatedLines, DEVSTACK_ENV_END].join('\n')

	if (startIndex === -1 && endIndex === -1) {
		const prefix = removeAuthoritativeEnvAssignments(existingEnv).trimEnd()
		return `${prefix}${prefix ? '\n\n' : ''}${nextBlock}\n`
	}
	if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
		throw new Error('Refusing to update .env: malformed devstack autogenerated block')
	}
	if (existingEnv.indexOf(DEVSTACK_ENV_START, startIndex + DEVSTACK_ENV_START.length) !== -1) {
		throw new Error('Refusing to update .env: multiple devstack autogenerated blocks')
	}

	const afterEnd = endIndex + DEVSTACK_ENV_END.length
	const before = removeAuthoritativeEnvAssignments(existingEnv.slice(0, startIndex))
	const after = removeAuthoritativeEnvAssignments(existingEnv.slice(afterEnd))
	return `${before}${nextBlock}${after}`
}

function containsAuthoritativeEnvAssignment(env: string): boolean {
	return env.split('\n').some((line) => AUTHORITATIVE_ENV_NAMES.some((name) => line.startsWith(`${name}=`)))
}

function removeAuthoritativeEnvAssignments(env: string): string {
	return env
		.split('\n')
		.filter((line) => !AUTHORITATIVE_ENV_NAMES.some((name) => line.startsWith(`${name}=`)))
		.join('\n')
}

export function removeDevstackEnvBlock(existingEnv: string): string {
	const startIndex = existingEnv.indexOf(DEVSTACK_ENV_START)
	const endIndex = existingEnv.indexOf(DEVSTACK_ENV_END)

	if (startIndex === -1 && endIndex === -1) return existingEnv
	if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
		throw new Error('Refusing to update .env: malformed devstack autogenerated block')
	}
	if (existingEnv.indexOf(DEVSTACK_ENV_START, startIndex + DEVSTACK_ENV_START.length) !== -1) {
		throw new Error('Refusing to update .env: multiple devstack autogenerated blocks')
	}

	let before = existingEnv.slice(0, startIndex)
	let after = existingEnv.slice(endIndex + DEVSTACK_ENV_END.length)
	if (before.endsWith('\n\n')) before = before.slice(0, -1)
	if (before.endsWith('\n') && after.startsWith('\n')) after = after.slice(1)
	return `${before}${after}`
}

function envName(name: string): string {
	return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()
}

export type StackEnvProjection = {
	id: string
	worktreePath?: string
	composeProject: string
	nativeIcon?: string
	tabColor?: string
	ports: Record<string, number>
	postgres: {
		postgresPort: number
		postgresPassword: string
		postgresVolume: string
		databaseUrl: string
		readReplicaDatabaseUrl: string
	}
	api?: { port: number; route: string }
	electric?: {
		electricPort: number
		electricProxyPort: number
		electricSecret: string
		electricReplicationStreamId: string
		shapeUrl: string
		syncRoute: string
	}
	rivet?: { enginePort: number; servicesPort: number; engineVolume: string; durableStreamsOrigin: string }
	minio?: {
		apiPort: number
		consolePort: number
		volume: string
		bucket: string
		accessKeyId: string
		secretAccessKey: string
		endpoint: string
	}
	redis?: {
		port: number
		volume: string
		url: string
	}
	testServices?: {
		composeProject: string
		postgresPort: number
		postgresPassword: string
		postgresVolume: string
		electricPort: number
		electricSecret: string
		electricReplicationStreamId: string
		rivetEnginePort: number
		rivetServicesPort: number
		rivetEngineVolume: string
		redis: NonNullable<StackEnvProjection['redis']>
	}
	routes?: { ui: string; adminApi?: string; s3?: string }
}

export function renderStackEnvLines(
	stack: StackEnvProjection,
	registryPath: string,
	organizationId?: string,
): string[] {
	const apiPort = stack.api?.port ?? stack.ports.api
	const apiRoute = stack.api?.route ?? `https://api.${stack.id}.localhost`
	const syncRoute = stack.electric?.syncRoute ?? `https://sync.${stack.id}.localhost`
	const uiRoute = stack.routes?.ui ?? `https://app.${stack.id}.localhost`
	const adminApiRoute = stack.routes?.adminApi ?? `https://admin-api.${stack.id}.localhost`
	const lines: string[] = [
		`DEVSTACK_ID=${stack.id}`,
		`DEVSTACK_REGISTRY_PATH=${registryPath}`,
		`LOG_BASE=${stackLogDirectory(stack.id)}`,
		`DEVSTACK_COMPOSE_PROJECT=${stack.composeProject}`,
		`DEVSTACK_POSTGRES_PORT=${stack.postgres.postgresPort}`,
		`DEVSTACK_POSTGRES_PASSWORD=${stack.postgres.postgresPassword}`,
		`DEVSTACK_POSTGRES_VOLUME=${stack.postgres.postgresVolume}`,
		`DATABASE_URL=${stack.postgres.databaseUrl}`,
		`READ_REPLICA_DATABASE_URL=${stack.postgres.readReplicaDatabaseUrl}`,
		`RIPTIDE_API_PORT=${apiPort}`,
		`VITE_PUBLIC_RIPTIDE_API_ORIGIN=${apiRoute}`,
		`RIPTIDE_API_ORIGIN=${apiRoute}`,
		`RIPTIDE_UI_PORT=${stack.ports.ui}`,
		`RIPTIDE_CLOUD_PORT=${stack.ports.cloud}`,
		`RIPTIDE_UI_TANSTACK_DEVTOOLS_PORT=${stack.ports.tanstackDevtools}`,
		`VITE_PUBLIC_DEEP_LINK_SCHEME=riptide-local-${stack.id.slice(0, 40)}`,
		`VITE_PUBLIC_CLOUD_ORIGIN=https://cloud.${stack.id}.localhost`,
		`CLOUD_ORIGIN=https://cloud.${stack.id}.localhost`,
		`VITE_ADMIN_API_ORIGIN=${adminApiRoute}`,
		`APP_ORIGIN=${uiRoute}`,
		`RIPTIDE_ELECTRON_RENDERER_URL=${uiRoute}`,
		`DEVSTACK_ELECTRIC_PORT=${stack.electric?.electricPort ?? stack.ports.electric}`,
		`DEVSTACK_ELECTRIC_SECRET=${stack.electric?.electricSecret ?? ''}`,
		`DEVSTACK_ELECTRIC_REPLICATION_STREAM_ID=${stack.electric?.electricReplicationStreamId ?? stack.id}`,
		`RIPTIDE_ELECTRIC_PROXY_PORT=${stack.electric?.electricProxyPort ?? stack.ports.electricProxy}`,
		`ELECTRIC_SHAPE_URL=${stack.electric?.shapeUrl ?? `http://127.0.0.1:${stack.ports.electric}/v1/shape`}`,
		`ELECTRIC_SECRET=${stack.electric?.electricSecret ?? ''}`,
		`VITE_PUBLIC_SYNC_ORIGIN=${syncRoute}`,
		`RIPTIDE_SYNC_ORIGIN=${syncRoute}`,
		`RIPTIDE_APP_ORIGIN=${uiRoute}`,
		`VITE_PUBLIC_DEVSTACK_ID=${stack.id}`,
	]
	if (stack.tabColor) lines.push(`VITE_PUBLIC_DEVSTACK_COLOR=${stack.tabColor.slice(1)}`)
	lines.push('VITE_PUBLIC_DEVSTACK_OVERRIDE_DEFAULT_CLAUDE_MODEL=haiku', 'VITE_PUBLIC_BUILD_TYPE=local')
	if (stack.nativeIcon) {
		lines.push(`DEVSTACK_NATIVE_ICON=${joinNativeIconPath(stack.worktreePath, stack.nativeIcon)}`)
	}
	lines.push(
		`RIPTIDE_DAEMON_API_ORIGIN=${apiRoute}`,
		`RIPTIDE_DAEMON_SYNC_ORIGIN=${syncRoute}`,
		`RIPTIDE_DAEMON_CLOUD_ORIGIN=https://cloud.${stack.id}.localhost`,
		`RIPTIDE_DAEMON_APP_ORIGIN=${uiRoute}`,
		`DEVSTACK_DURABLE_STREAMS_PORT=${stack.rivet?.servicesPort ?? stack.ports.rivetServices}`,
		`DEVSTACK_DURABLE_STREAMS_VOLUME=${stack.rivet?.engineVolume ?? `${stack.composeProject}-durable-streams`}`,
		`DURABLE_STREAMS_ORIGIN=${stack.rivet?.durableStreamsOrigin ?? `http://127.0.0.1:${stack.ports.rivetServices}`}`,
		`DEVSTACK_MINIO_API_PORT=${stack.minio?.apiPort ?? stack.ports.minioApi}`,
		`DEVSTACK_MINIO_CONSOLE_PORT=${stack.minio?.consolePort ?? stack.ports.minioConsole}`,
		`DEVSTACK_MINIO_VOLUME=${stack.minio?.volume ?? `${stack.composeProject}-minio`}`,
		// The Caddy https route, not the direct http port: WebKit (the native app's
		// webview) blocks plain-http presigned S3 PUTs from an https page as mixed content.
		`S3_ARTIFACTS_ENDPOINT=${stack.routes?.s3 ?? stack.minio?.endpoint ?? `http://127.0.0.1:${stack.ports.minioApi}`}`,
		`S3_ARTIFACTS_BUCKET=${stack.minio?.bucket ?? 'riptide-artifacts'}`,
		`S3_ACCESS_KEY_ID=${stack.minio?.accessKeyId ?? 'minioadmin'}`,
		`S3_SECRET_ACCESS_KEY=${stack.minio?.secretAccessKey ?? 'minioadmin'}`,
	)
	if (organizationId) lines.push(`RIPTIDE_DAEMON_ORGANIZATION_ID=${organizationId}`)
	if (stack.redis) {
		lines.push(
			`DEVSTACK_REDIS_PORT=${stack.redis.port}`,
			`DEVSTACK_REDIS_VOLUME=${stack.redis.volume}`,
			`KV_URL=${stack.redis.url}`,
			`LOCAL_REDIS_URL=${stack.redis.url}`,
		)
	}
	if (stack.testServices) {
		lines.push(
			`HUMANLAYER_TEST_COMPOSE_PROJECT=${stack.testServices.composeProject}`,
			`DEVSTACK_TEST_POSTGRES_PORT=${stack.testServices.postgresPort}`,
			`DEVSTACK_TEST_POSTGRES_PASSWORD=${stack.testServices.postgresPassword}`,
			`DEVSTACK_TEST_POSTGRES_VOLUME=${stack.testServices.postgresVolume}`,
			`DEVSTACK_TEST_ELECTRIC_PORT=${stack.testServices.electricPort}`,
			`DEVSTACK_TEST_ELECTRIC_SECRET=${stack.testServices.electricSecret}`,
			`DEVSTACK_TEST_ELECTRIC_REPLICATION_STREAM_ID=${stack.testServices.electricReplicationStreamId}`,
			`DEVSTACK_TEST_DURABLE_STREAMS_PORT=${stack.testServices.rivetServicesPort}`,
			`DEVSTACK_TEST_DURABLE_STREAMS_VOLUME=${stack.testServices.rivetEngineVolume}`,
			`DEVSTACK_TEST_REDIS_PORT=${stack.testServices.redis.port}`,
			`DEVSTACK_TEST_REDIS_VOLUME=${stack.testServices.redis.volume}`,
			`HUMANLAYER_TEST_POSTGRES_ADMIN_URL=postgresql://postgres:${encodeURIComponent(stack.testServices.postgresPassword)}@127.0.0.1:${stack.testServices.postgresPort}/postgres`,
			`HUMANLAYER_TEST_POSTGRES_DATABASE_URL_TEMPLATE=postgresql://postgres:${encodeURIComponent(stack.testServices.postgresPassword)}@127.0.0.1:${stack.testServices.postgresPort}/{database}`,
			`HUMANLAYER_TEST_ELECTRIC_URL=http://127.0.0.1:${stack.testServices.electricPort}`,
			`HUMANLAYER_TEST_ELECTRIC_SECRET=${stack.testServices.electricSecret}`,
			`HUMANLAYER_TEST_KV_URL=${stack.testServices.redis.url}`,
			`HUMANLAYER_TEST_DURABLE_STREAMS_ORIGIN=http://127.0.0.1:${stack.testServices.rivetServicesPort}`,
		)
	}
	lines.push(
		...Object.entries(stack.ports)
			.filter(
				([name]) =>
					![
						'postgres',
						'ui',
						'cloud',
						'electric',
						'electricProxy',
						'rivetEngine',
						'rivetServices',
						'minioApi',
						'minioConsole',
						'tanstackDevtools',
					].includes(name),
			)
			.map(([name, port]) => `DEVSTACK_${envName(name)}_PORT=${port}`),
	)
	return lines
}

export function stackLogDirectory(stackId: string): string {
	return join(homedir(), '.humanlayer', 'riptide', 'logs', stackId)
}

function joinNativeIconPath(worktreePath: string | undefined, nativeIcon: string): string {
	return worktreePath ? `${worktreePath}/apps/riptide-native/${nativeIcon}` : nativeIcon
}
import { homedir } from 'node:os'
import { join } from 'node:path'
